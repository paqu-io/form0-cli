export function createReadmeTemplate(projectName) {
  return `# ${projectName}

Generated by \`form0 init\`.

The starter is **Building Inspection & Maintenance Plan**, a self-contained example of
field types, calculations, conditional behavior, building plans, repeatables, and events.

## Files

- \`package.json\` - Node.js project configuration
- \`form.schema.json\` - Your form schema definition
- \`test.js\` - Test script to validate your form
- \`README.md\` - This file
- \`supporting-images/\` - Bundled evidence photo guide

## Setup

First, install dependencies:
\`\`\`bash
npm install
\`\`\`

## Usage

### Test your form
\`\`\`bash
form0 test
# or
node test.js
\`\`\`

### Run with custom values
\`\`\`bash
form0 run form.schema.json --values '{"building_ref":"BLD-001","building_name":"Riverside Hall","assessor":"Alex Morgan","overall_condition":"good"}'
\`\`\`

### Validate schema
\`\`\`bash
form0 validate form.schema.json
\`\`\`

### Preview form structure
\`\`\`bash
form0 preview form.schema.json
\`\`\`

### Watch for changes
\`\`\`bash
form0 watch form.schema.json --auto-run
\`\`\`

### Try the interactive form
\`\`\`bash
form0 serve form.schema.json
\`\`\`

Open the preview URL printed in the terminal. Enter an assessor, then choose **Yes** for
**Use assessor as follow-up contact** to copy the name. Selecting **Urgent follow-up** for
the overall condition opens guidance and reveals required observation details. Try the
area/allowance calculations, add an inspected area and a nested observation, and open the
optional building layout. Evidence notes show the photo guide inline; urgent observation
details retain an image icon that opens the guide in a dialog.

\`test.js\` uses complete sample values for the required fields and demonstrates applying
a \`SETVALUE\` event operation when using core directly. Derived amounts stay in calculated
fields; record and row validation events use \`INVALID\`.
`;
}
